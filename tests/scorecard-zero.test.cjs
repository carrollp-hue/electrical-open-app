const assert = require('node:assert/strict');
global.window = {};
require('../scorecard-zero.js');
const { equal, differences, holeScore } = window.electricalOpenScorecardZero;
const hole = { par: 4, stroke_index: 3 };
assert.equal(equal(0, 8, hole, 28), true);
assert.equal(equal(8, 0, hole, 28), true);
assert.equal(equal(0, 7, hole, 28), false);
assert.equal(equal(0, 9, hole, 28), false);
assert.equal(equal(0, 8, hole, null), false);
assert.equal(equal(null, 0, hole, 28), false);
assert.equal(equal(0, 0, hole, null), true);
assert.equal(equal(4, 4, hole, 28), true);
assert.equal(equal(4, 5, hole, 28), false);
assert.deepEqual(differences(Array(18).fill(0), Array(18).fill(8), Array(18).fill(hole), 28), []);
assert.equal(differences([], [], [], 28), null);
assert.deepEqual(holeScore(0, hole, 28), { gross: 8, nett: 6, points: 0, adjusted: 8 });
assert.deepEqual(holeScore(0, { par: 4, stroke_index: 15 }, 28), { gross: 7, nett: 6, points: 0, adjusted: 7 });
assert.deepEqual(holeScore(9, { par: 4, stroke_index: 15 }, 28), { gross: 9, nett: 8, points: 0, adjusted: 7 });
assert.equal(holeScore(null, hole, 28), null);
assert.equal(holeScore(0, hole, 29), null);
console.log('Scorecard zero comparison tests passed.');
